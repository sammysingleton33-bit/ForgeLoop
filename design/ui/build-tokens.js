// Generates prototype/tokens.css and prototype/tokens.js from tokens.json (run from design/ui: node build-tokens.js).
const fs = require("fs");
const path = require("path");
const tokens = JSON.parse(fs.readFileSync(path.join(__dirname, "tokens.json"), "utf8"));

const lines = [":root {"];
for (const group of ["color", "resource", "rarity", "tincture"]) {
	for (const [k, v] of Object.entries(tokens[group])) lines.push(`\t--${group}-${k}: ${v};`);
}
for (const [k, v] of Object.entries(tokens.textSize)) lines.push(`\t--text-${k}: ${v}px;`);
for (const [k, v] of Object.entries(tokens.radius)) lines.push(`\t--radius-${k}: ${v}px;`);
tokens.space.forEach((v, i) => lines.push(`\t--space-${i}: ${v}px;`));
lines.push(`\t--font-display: "${tokens.font.display}", serif;`);
lines.push(`\t--font-heading: "${tokens.font.heading}", serif;`);
lines.push(`\t--font-body: "${tokens.font.body}", sans-serif;`);
lines.push(`\t--touch: ${tokens.touchTarget}px;`);
lines.push(`\t--trim: ${tokens.stroke.trim}px;`);
lines.push("}");

const fontFaces = [];
const faces = [
	["Grenze Gotisch", "grenze-gotisch", [600, 700]],
	["Merriweather", "merriweather", [400, 700, 900]],
	["Montserrat", "montserrat", [500, 600, 700, 800]],
];
for (const [family, pkg, weights] of faces) {
	for (const w of weights) {
		fontFaces.push(
			`@font-face { font-family: "${family}"; font-weight: ${w}; font-style: normal; ` +
				`src: url("../node_modules/@fontsource/${pkg}/files/${pkg}-latin-${w}-normal.woff2") format("woff2"); }`
		);
	}
}
fs.mkdirSync(path.join(__dirname, "prototype"), { recursive: true });
fs.writeFileSync(
	path.join(__dirname, "prototype", "tokens.css"),
	"/* Generated by design/ui/build-tokens.js from tokens.json. Do not edit. */\n" +
		fontFaces.join("\n") +
		"\n" +
		lines.join("\n") +
		"\n"
);
fs.writeFileSync(
	path.join(__dirname, "prototype", "tokens.js"),
	"// Generated by design/ui/build-tokens.js from tokens.json. Do not edit.\nwindow.TOKENS = " + JSON.stringify(tokens, null, "\t") + ";\n"
);
console.log("wrote prototype/tokens.css and prototype/tokens.js");
